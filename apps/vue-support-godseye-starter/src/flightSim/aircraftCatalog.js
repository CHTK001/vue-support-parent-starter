/** Every aircraft the simulator knows about, keyed by id. */
const CATALOG = Object.freeze({
  [BOEING_747_200B.id]: BOEING_747_200B,
});

/** The aircraft selected when the planner opens. */
export const DEFAULT_AIRCRAFT_ID = BOEING_747_200B.id;

/**
 * Every catalog entry, in display order.
 *
 * @returns {Array<object>} Aircraft definitions.
 */
export function listAircraft() {
  return Object.values(CATALOG);
}

/**
 * Only the aircraft users may currently select.
 *
 * Entries can be authored ahead of their asset landing by setting
 * `available: false`; they stay out of the picker until the model exists.
 *
 * @returns {Array<object>} Selectable aircraft definitions.
 */
export function listAvailableAircraft() {
  return listAircraft().filter((a) => a.available);
}

/**
 * Look up one aircraft.
 *
 * @param {string} id - Catalog id.
 * @returns {object|null} The definition, or null when unknown.
 */
export function getAircraft(id) {
  return CATALOG[id] || null;
}

/**
 * Validate a catalog entry.
 *
 * The physics engine divides by several of these, so a missing or zero value
 * would surface as NaN telemetry mid-flight rather than as a clear error at
 * startup. Exported so a test can assert every shipped entry is well-formed.
 *
 * @param {object} aircraft - Candidate definition.
 * @returns {string[]} Problems found; empty means valid.
 */
export function validateAircraft(aircraft) {
  const problems = [];
  if (!aircraft || typeof aircraft !== 'object') return ['aircraft is not an object'];

  const requiredStrings = ['id', 'name', 'manufacturer', 'modelUrl'];
  for (const key of requiredStrings) {
    if (typeof aircraft[key] !== 'string' || !aircraft[key]) problems.push(`${key} must be a non-empty string`);
  }

  // Anything used as a divisor or a rate must be finite and positive.
  const requiredPositive = [
    'massKg', 'wingAreaM2', 'wingspanM', 'maxThrustPerEngineN', 'engineCount',
    'liftSlopePerRad', 'stallAlphaRad', 'cd0', 'vneMps', 'vStallCleanMps',
    'maxRollRateRadS', 'maxPitchRateRadS', 'maxYawRateRadS',
    'rollInertiaS', 'pitchInertiaS', 'yawInertiaS',
    'gearTransitS', 'flapTransitS', 'spoilerTransitS',
  ];
  for (const key of requiredPositive) {
    const value = aircraft[key];
    if (!Number.isFinite(value) || value <= 0) problems.push(`${key} must be a positive finite number`);
  }

  if (!Array.isArray(aircraft.flapDetents) || aircraft.flapDetents.length === 0) {
    problems.push('flapDetents must be a non-empty array');
  } else {
    if (aircraft.flapDetents[0] !== 0) problems.push('flapDetents must start at 0');
    for (let i = 1; i < aircraft.flapDetents.length; i += 1) {
      if (aircraft.flapDetents[i] <= aircraft.flapDetents[i - 1]) {
        problems.push('flapDetents must be strictly ascending');
        break;
      }
    }
  }

  if (aircraft.vStallCleanMps >= aircraft.vneMps) problems.push('vStallCleanMps must be below vneMps');

  const anchors = aircraft.cameraAnchors;
  if (!anchors || typeof anchors !== 'object') {
    problems.push('cameraAnchors is required');
  } else {
    for (const view of ['chase', 'nose', 'wing', 'orbit']) {
      const a = anchors[view];
      if (!a || !Number.isFinite(a.forward) || !Number.isFinite(a.right) || !Number.isFinite(a.up)) {
        problems.push(`cameraAnchors.${view} needs finite forward/right/up`);
      }
    }
  }

  const ap = aircraft.autopilot;
  if (!ap || typeof ap !== 'object') {
    problems.push('autopilot config is required');
  } else {
    for (const key of ['maxBankRad', 'headingGain', 'altitudeGain', 'maxVerticalSpeedMps', 'targetSpeedMps']) {
      if (!Number.isFinite(ap[key]) || ap[key] <= 0) problems.push(`autopilot.${key} must be a positive finite number`);
    }
  }

  return problems;
}
