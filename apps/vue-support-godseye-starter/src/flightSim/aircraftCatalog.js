/**
 * Flight Sim aircraft catalog.
 *
 * Every aircraft-specific number lives here — the physics engine
 * (`flightDynamics.js`) reads them and contains no type-specific constants, so
 * adding an aircraft is a catalog entry rather than a physics change.
 *
 * Units are SI throughout (metres, seconds, kilograms, Newtons, radians).
 * Knots / feet / FPM exist only in the HUD layer.
 *
 * MODEL CONVENTION — matches the bundled fleet documented in
 * `public/models/README.md`: glTF +Y-up, nose toward local −X, real-world metre
 * scale, bounding-box centre at the origin. A new model must be baked the same
 * way or given a correcting `modelOrientation`.
 *
 * CONTROL SURFACES — `controlSurfaces` maps our semantic control names onto
 * candidate node-name patterns in the GLB. Nothing here is assumed to exist:
 * `simAircraftRenderer` resolves each against the real loaded hierarchy and
 * silently skips whatever is absent. Run `node scripts/inspect-model.mjs
 * <file.glb>` to see what an asset actually contains before writing a mapping.
 */

