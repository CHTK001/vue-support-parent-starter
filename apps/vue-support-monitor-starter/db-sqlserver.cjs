const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  console.log('访问数据库管理页面...');
  await page.goto('http://127.0.0.1:8848/#/db-manager?datasourceId=1003', { waitUntil: 'networkidle', timeout: 30000 });
  await page.waitForTimeout(5000);
  const title = await page.title();
  console.log('页面标题:', title);
  await page.screenshot({ path: 'test-results/db-sqlserver-initial.png', fullPage: true });
  console.log('初始截图已保存');
  const bodyText = await page.locator('body').innerText();
  console.log('页面文本长度:', bodyText.length);
  console.log('包含SQL Server:', bodyText.includes('SQL') || bodyText.includes('sql'));
  console.log('包含master:', bodyText.includes('master'));
  console.log('包含表:', bodyText.includes('表') || bodyText.includes('table'));
  console.log('包含错误:', bodyText.includes('错误') || bodyText.includes('error') || bodyText.includes('Error'));
  console.log('包含连接失败:', bodyText.includes('连接失败') || bodyText.includes('failed'));
  await browser.close();
  console.log('完成!');
})();
