<!--
  新建表对话框（数据库管理器专用）—— **设计表**，不是 DDL 文本框。

  <p>与 `components/selectors/DdlPreviewDialog.vue`（数据源中心的建表 / 补列，打开即预览 DDL）是**两件事**，不要合并：
  那一个按「列名 + 主键列」推断类型后走 hub 的 DDL 接口（没有 database 参数，只会建到连接默认库），
  也不提供逐列编辑；这一个面向 Navicat 式手工建表，必须支持指定目标库与逐列属性。</p>

  <p><b>界面即模型</b>：一行一列（字段名 / 类型 / 长度 / 小数位 / 可空 / 主键 / 自增 / 默认值 / 注释），
  提交给后端 `POST /ms/monitor/db/table` 的 `columns`。**前端不拼 CREATE TABLE** ——
  引号（MySQL 反引号 vs 其余内核的双引号）、内联 COMMENT、自增写法
  （AUTO_INCREMENT vs GENERATED BY DEFAULT AS IDENTITY）全在后端方言层选，
  见 `DbDialectSupport.createTable`。所以这里既不出现 SQL 文本框，也不会出现
  「MySQL 能建、H2 报语法错」这类只对一个内核成立的语句。</p>

  <p>列类型与长度 / 小数位的适用范围取自 `utils/columnTypes.ts`，与设计视图、列属性对话框同一份；
  校验口径镜像后端 `DbColumnDef`（构造期就会拒绝，这里是提前提示，不是少校验一层）。</p>

  <p><b>可预填</b>（initialName / initialColumns）：数据同步向导在预览发现「表不存在」时，
  会带着缺失的表名与源表列打开本对话框；created 事件回传（库名, 最终表名），宿主据此
  回填并继续预览。不传这两个 prop 时行为与历史完全一致 —— 打开即空白单列。</p>
-->
<script setup lang="ts">
import { message } from "@repo/core";
import { computed, ref, watch } from "vue";

import ReButton from "@repo/ui/re-button";
import ReDialog from "@repo/ui/re-dialog";
import ReInput from "@repo/ui/re-input";
import DesignColumnGrid from "./DesignColumnGrid.vue";
import { newDesignRow, parseEnumValues, type DesignColumnRow } from "./designColumnModel";
import { createDbTable } from "../../api/manageConsoles";
import type { DbColumnPayload } from "../../api/dbManageApi";
import { ENUM_LIKE_TYPES, typeAllowsScale, typeNeedsSize } from "../../utils/columnTypes";

/** 设计网格的一行（共享模型，见 designColumnModel） */
type DesignColumn = DesignColumnRow;

const props = withDefaults(
  defineProps<{
    /** 对话框可见性（v-model） */
    modelValue: boolean;
    /** 目标库名 */
    database?: string;
    /** 数据源 ID */
    datasourceId?: number;
    /** 预填表名（数据同步预览发现「表不存在」时把缺失表名带进来；默认空） */
    initialName?: string;
    /** 预填列（目标侧缺表时从源表元数据带入；默认空 = 打开即空白单列，与历史一致） */
    initialColumns?: Array<{
      name: string;
      type?: string;
      size?: number | null;
      scale?: number | null;
      nullable?: boolean;
      primaryKey?: boolean;
      autoIncrement?: boolean;
      defaultValue?: string;
      comment?: string;
      enumText?: string;
    }>;
  }>(),
  {
    database: "",
    datasourceId: undefined,
    initialName: "",
    initialColumns: () => [],
  },
);

const emit = defineEmits<{
  (e: "update:modelValue", value: boolean): void;
  /** 建表成功（带上库名与最终表名：宿主据此刷新表树 / 回填表名继续业务流程） */
  (e: "created", database: string, table: string): void;
}>();

const name = ref("");
const remark = ref("");
const rows = ref<DesignColumn[]>([newDesignRow()]);
const busy = ref(false);
const error = ref("");

/** 新建一行（共享模型） */
const newRow = (partial: Partial<DesignColumn> = {}): DesignColumn => newDesignRow(partial);

/** 有表名且至少填了一列才能提交 */
const canSubmit = computed(() => Boolean(name.value.trim()) && rows.value.some(r => r.name.trim()));

/** 每次打开都清空上一次的内容与报错 */
watch(
  () => props.modelValue,
  open => {
    if (!open) {
      return;
    }
    // 预填表名与列（数据同步的「设计表」流程会带缺失表名与源表列进来）；
    // 没给预填时保持历史行为：打开即清空、一行空白列
    name.value = props.initialName || "";
    remark.value = "";
    rows.value = props.initialColumns.length
      ? props.initialColumns.map(c =>
          newRow({
            name: c.name,
            type: c.type || "VARCHAR",
            size: c.size ?? null,
            scale: c.scale ?? null,
            nullable: c.nullable ?? true,
            primaryKey: c.primaryKey ?? false,
            autoIncrement: c.autoIncrement ?? false,
            defaultValue: c.defaultValue || "",
            comment: c.comment || "",
            enumText: c.enumText || "",
          }),
        )
      : [newRow()];
    error.value = "";
  },
);

/** 加一列 */
function addRow(): void {
  rows.value.push(newRow());
}

/** 删一列（共享网格回调；删空了也允许，提交前会拦） */
function removeRow(row: DesignColumn): void {
  const i = rows.value.indexOf(row);
  if (i >= 0) rows.value.splice(i, 1);
}

/**
 * 提交前校验。
 *
 * <p>都是**能在界面上说清楚**的问题（缺长度、列名重、枚举没给取值），
 * 不代替后端校验：后端 `DbColumnDef` 构造期还会再过一遍白名单。</p>
 *
 * @param filled 已填字段名的行
 * @returns 空串表示通过，否则是可读错误
 */
function validate(filled: DesignColumn[]): string {
  if (!name.value.trim()) {
    return "请填写表名";
  }
  if (filled.length === 0) {
    return "至少填写一列";
  }
  const seen = new Set<string>();
  for (let i = 0; i < filled.length; i++) {
    const row = filled[i];
    const column = row.name.trim();
    const no = i + 1;
    if (!/^[A-Za-z0-9_]+$/.test(column) || column.length > 64) {
      return `第 ${no} 列名不合法（字母、数字、下划线，最长 64 字符）：${column || "（空）"}`;
    }
    const key = column.toLowerCase();
    if (seen.has(key)) {
      return `列名重复：${column}`;
    }
    seen.add(key);
    if (typeNeedsSize(row.type) && !(row.size && row.size > 0)) {
      return `第 ${no} 列（${row.type}）必须填写长度`;
    }
    if (ENUM_LIKE_TYPES.has(row.type) && parseEnumValues(row.enumText).length === 0) {
      return `第 ${no} 列（${row.type}）必须填写取值（用逗号分隔）`;
    }
  }
  return "";
}

async function submit(): Promise<void> {
  const filled = rows.value.filter(r => r.name.trim());
  const invalid = validate(filled);
  if (invalid) {
    error.value = invalid;
    return;
  }
  const table = name.value.trim();
  busy.value = true;
  error.value = "";
  try {
    const columns: DbColumnPayload[] = filled.map(row => ({
      columnName: row.name.trim(),
      type: row.type,
      // 只把「该类型用得上的长度/小数位」发过去：类型是 VARCHAR 时留着 255 没问题，
      // 但把长度发给 INT 会被内核当成 INT(11) 一类的写法，H2 直接拒。
      size: typeNeedsSize(row.type) ? (row.size ?? undefined) : undefined,
      scale: typeAllowsScale(row.type) ? (row.scale ?? undefined) : undefined,
      nullable: row.nullable,
      autoIncrement: row.autoIncrement,
      defaultValue: row.defaultValue.trim() || undefined,
      comment: row.comment.trim() || undefined,
      enumValues: ENUM_LIKE_TYPES.has(row.type) ? parseEnumValues(row.enumText) : undefined,
    }));
    await createDbTable({
      table,
      columns,
      primaryKey: filled.filter(row => row.primaryKey).map(row => row.name.trim()),
      comment: remark.value.trim() || undefined,
      datasourceId: props.datasourceId,
      database: props.database || undefined,
    });
    message.success(`表 ${table} 创建成功`);
    emit("created", props.database, table);
    emit("update:modelValue", false);
  } catch (e) {
    // 建表失败原因（内核不支持、类型/长度被拒等）要原样给出，用户据此改设计
    error.value = String((e as Error)?.message ?? e);
  } finally {
    busy.value = false;
  }
}
</script>

<template>
  <ReDialog
    :model-value="modelValue"
    title="新建表（设计表）"
    width="min(860px, 66vw)"
    @update:model-value="(v: unknown) => emit('update:modelValue', Boolean(v))"
  >
    <div class="ct">
      <div class="ct-head">
        <div class="ct-form__item">
          <label>目标库</label>
          <ReInput :model-value="database" disabled />
        </div>
        <div class="ct-form__item">
          <label>表名</label>
          <ReInput v-model="name" placeholder="请输入表名" />
        </div>
        <div class="ct-form__item ct-form__item--wide">
          <label>表注释</label>
          <ReInput v-model="remark" placeholder="请输入表注释" />
        </div>
      </div>

      <div class="ct-grid-bar">
        <span class="ct-grid-bar__title">列设计</span>
        <span class="ct-grid-bar__hint">勾主键 / 自增会自动把该列置为「不可空」</span>
        <span class="ct-spacer" />
        <ReButton layout="square" type="primary" icon="Plus" tip="添加一列" @click="addRow" />
      </div>

      <!-- 列设计网格：共享组件 DesignColumnGrid（与数据库管理器的表结构视图同一份实现）。
           列清单、单元格控件、类型显隐规则都在那里维护，这里只管表名/注释/校验/提交。 -->
      <div class="ct-grid">
        <DesignColumnGrid
          :rows="rows"
          mode="new"
          max-height="40vh"
          empty-text="还没有列，点右上角「添加一列」开始设计"
          @remove-row="removeRow"
        />
      </div>

      <p class="ct-form__tip">
        引号、列注释与自增写法由后端按目标库内核选择（MySQL 用反引号与 AUTO_INCREMENT，
        H2 / PostgreSQL 用双引号与 GENERATED BY DEFAULT AS IDENTITY），这里只描述结构。
      </p>
      <p v-if="error" class="ct-form__error">{{ error }}</p>
    </div>
    <template #footer>
      <ReButton @click="emit('update:modelValue', false)">取消</ReButton>
      <ReButton type="primary" :loading="busy" :disabled="!canSubmit" @click="submit">创建</ReButton>
    </template>
  </ReDialog>
</template>

