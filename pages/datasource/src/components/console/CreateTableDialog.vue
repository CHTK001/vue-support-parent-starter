<!--
  新建表对话框（数据库管理器专用）—— **设计表**，不是 DDL 文本框。

  <p>与 `components/selectors/CreateTableDialog.vue`（数据源中心的建表 / 补列）是**两件事**，不要合并：
  那一个走 hub 的 DDL 接口（没有 database 参数，只会建到连接默认库）；
  这一个面向 Navicat 式手工建表，必须支持指定目标库。</p>

  <p><b>界面即模型</b>：一行一列（字段名 / 类型 / 长度 / 小数位 / 可空 / 主键 / 自增 / 默认值 / 注释），
  提交给后端 `POST /ms/monitor/db/table` 的 `columns`。**前端不拼 CREATE TABLE** ——
  引号（MySQL 反引号 vs 其余内核的双引号）、内联 COMMENT、自增写法
  （AUTO_INCREMENT vs GENERATED BY DEFAULT AS IDENTITY）全在后端方言层选，
  见 `DbDialectSupport.createTable`。所以这里既不出现 SQL 文本框，也不会出现
  「MySQL 能建、H2 报语法错」这类只对一个内核成立的语句。</p>

  <p>列类型与长度 / 小数位的适用范围取自 `utils/columnTypes.ts`，与设计视图、列属性对话框同一份；
  校验口径镜像后端 `DbColumnDef`（构造期就会拒绝，这里是提前提示，不是少校验一层）。</p>

  <p><b>可预填</b>（initialName / initialColumns）：数据同步向导在预览发现「表不存在」时，
  会带着缺失的表名与源表列打开本对话框；created 事件回传（库名, 最终表名），宿主据此
  回填并继续预览。不传这两个 prop 时行为与历史完全一致 —— 打开即空白单列。</p>
-->
<script setup lang="ts">
import { computed, ref, watch } from "vue";
import { ElMessage } from "element-plus";
import ReButton from "@repo/ui/re-button";
import ReDialog from "@repo/ui/re-dialog";
import ReInput from "@repo/ui/re-input";
import ReInputNumber from "@repo/ui/re-input-number";
import ReSelect from "@repo/ui/re-select";
import { ReRadioButton, ReRadioGroup } from "@repo/ui/re-kit";
import { createDbTable } from "../../api/manageConsoles";
import type { DbColumnPayload } from "../../api/dbManageApi";
import { columnTypeSelectOptions, ENUM_LIKE_TYPES, typeAllowsScale, typeNeedsSize } from "../../utils/columnTypes";

/** 设计网格的一行，对应后端的一列 */
interface DesignColumn {
  /** 行的稳定 key：列名可能留空、也可能重名，不能拿 name 当 key */
  key: number;
  /** 字段名 */
  name: string;
  /** 类型 */
  type: string;
  /** 长度（只对 typeNeedsSize 的类型有意义） */
  size: number | null;
  /** 小数位（只对 typeAllowsScale 的类型有意义） */
  scale: number | null;
  /** 可空 */
  nullable: boolean;
  /** 是否主键 */
  primaryKey: boolean;
  /** 是否自增 */
  autoIncrement: boolean;
  /** 默认值原文（交给后端按类型落） */
  defaultValue: string;
  /** 列注释 */
  comment: string;
  /** ENUM / SET 的取值文本，逗号分隔 */
  enumText: string;
}

const props = withDefaults(
  defineProps<{
    /** 对话框可见性（v-model） */
    modelValue: boolean;
    /** 目标库名 */
    database?: string;
    /** 数据源 ID */
    datasourceId?: number;
    /** 预填表名（数据同步预览发现「表不存在」时把缺失表名带进来；默认空） */
    initialName?: string;
    /** 预填列（目标侧缺表时从源表元数据带入；默认空 = 打开即空白单列，与历史一致） */
    initialColumns?: Array<{
      name: string;
      type?: string;
      size?: number | null;
      scale?: number | null;
      nullable?: boolean;
      primaryKey?: boolean;
      autoIncrement?: boolean;
      defaultValue?: string;
      comment?: string;
      enumText?: string;
    }>;
  }>(),
  {
    database: "",
    datasourceId: undefined,
    initialName: "",
    initialColumns: () => [],
  },
);

const emit = defineEmits<{
  (e: "update:modelValue", value: boolean): void;
  /** 建表成功（带上库名与最终表名：宿主据此刷新表树 / 回填表名继续业务流程） */
  (e: "created", database: string, table: string): void;
}>();

/** 行 key 自增（数组里可能有多行同名/空名，key 必须唯一且稳定） */
let rowSeq = 0;

/** 新建一行：默认 VARCHAR(255) 可空，是多数场景的起点 */
const newRow = (partial: Partial<DesignColumn> = {}): DesignColumn => ({
  key: ++rowSeq,
  name: "",
  type: "VARCHAR",
  size: 255,
  scale: null,
  nullable: true,
  primaryKey: false,
  autoIncrement: false,
  defaultValue: "",
  comment: "",
  enumText: "",
  ...partial,
});

const name = ref("");
const remark = ref("");
const rows = ref<DesignColumn[]>([newRow()]);
const busy = ref(false);
const error = ref("");

/** 类型下拉项（分组） */
const typeOptions = computed(() => columnTypeSelectOptions());

/** 有表名且至少填了一列才能提交 */
const canSubmit = computed(() => Boolean(name.value.trim()) && rows.value.some(r => r.name.trim()));

/** 每次打开都清空上一次的内容与报错 */
watch(
  () => props.modelValue,
  open => {
    if (!open) {
      return;
    }
    // 预填表名与列（数据同步的「设计表」流程会带缺失表名与源表列进来）；
    // 没给预填时保持历史行为：打开即清空、一行空白列
    name.value = props.initialName || "";
    remark.value = "";
    rows.value = props.initialColumns.length
      ? props.initialColumns.map(c =>
          newRow({
            name: c.name,
            type: c.type || "VARCHAR",
            size: c.size ?? null,
            scale: c.scale ?? null,
            nullable: c.nullable ?? true,
            primaryKey: c.primaryKey ?? false,
            autoIncrement: c.autoIncrement ?? false,
            defaultValue: c.defaultValue || "",
            comment: c.comment || "",
            enumText: c.enumText || "",
          }),
        )
      : [newRow()];
    error.value = "";
  },
);

/** 加一列 */
function addRow(): void {
  rows.value.push(newRow());
}

/** 删一列（删空了也允许，提交前会拦） */
function removeRow(index: number): void {
  rows.value.splice(index, 1);
}

/**
 * 勾「主键」：主键列必非空（内核会把 PRIMARY KEY 当成 NOT NULL），
 * 与其让内核默默改写，不如在界面上直接把「可空」压成「否」并锁住。
 */
function togglePk(row: DesignColumn, value: unknown): void {
  row.primaryKey = value === true;
  if (row.primaryKey) {
    row.nullable = false;
  }
}

/** 勾「自增」：同上 —— 自增列不可空是后端构造期就拒绝的硬规则 */
function toggleAuto(row: DesignColumn, value: unknown): void {
  row.autoIncrement = value === true;
  if (row.autoIncrement) {
    row.nullable = false;
  }
}

/** ENUM / SET 取值文本 → 列表（去空白、去空项） */
function parseEnum(text: string): string[] {
  return text
    .split(",")
    .map(item => item.trim())
    .filter(Boolean);
}

/**
 * 提交前校验。
 *
 * <p>都是**能在界面上说清楚**的问题（缺长度、列名重、枚举没给取值），
 * 不代替后端校验：后端 `DbColumnDef` 构造期还会再过一遍白名单。</p>
 *
 * @param filled 已填字段名的行
 * @returns 空串表示通过，否则是可读错误
 */
function validate(filled: DesignColumn[]): string {
  if (!name.value.trim()) {
    return "请填写表名";
  }
  if (filled.length === 0) {
    return "至少填写一列";
  }
  const seen = new Set<string>();
  for (let i = 0; i < filled.length; i++) {
    const row = filled[i];
    const column = row.name.trim();
    const no = i + 1;
    if (!/^[A-Za-z0-9_]+$/.test(column) || column.length > 64) {
      return `第 ${no} 列名不合法（字母、数字、下划线，最长 64 字符）：${column || "（空）"}`;
    }
    const key = column.toLowerCase();
    if (seen.has(key)) {
      return `列名重复：${column}`;
    }
    seen.add(key);
    if (typeNeedsSize(row.type) && !(row.size && row.size > 0)) {
      return `第 ${no} 列（${row.type}）必须填写长度`;
    }
    if (ENUM_LIKE_TYPES.has(row.type) && parseEnum(row.enumText).length === 0) {
      return `第 ${no} 列（${row.type}）必须填写取值（用逗号分隔）`;
    }
  }
  return "";
}

async function submit(): Promise<void> {
  const filled = rows.value.filter(r => r.name.trim());
  const invalid = validate(filled);
  if (invalid) {
    error.value = invalid;
    return;
  }
  const table = name.value.trim();
  busy.value = true;
  error.value = "";
  try {
    const columns: DbColumnPayload[] = filled.map(row => ({
      columnName: row.name.trim(),
      type: row.type,
      // 只把「该类型用得上的长度/小数位」发过去：类型是 VARCHAR 时留着 255 没问题，
      // 但把长度发给 INT 会被内核当成 INT(11) 一类的写法，H2 直接拒。
      size: typeNeedsSize(row.type) ? (row.size ?? undefined) : undefined,
      scale: typeAllowsScale(row.type) ? (row.scale ?? undefined) : undefined,
      nullable: row.nullable,
      autoIncrement: row.autoIncrement,
      defaultValue: row.defaultValue.trim() || undefined,
      comment: row.comment.trim() || undefined,
      enumValues: ENUM_LIKE_TYPES.has(row.type) ? parseEnum(row.enumText) : undefined,
    }));
    await createDbTable({
      table,
      columns,
      primaryKey: filled.filter(row => row.primaryKey).map(row => row.name.trim()),
      comment: remark.value.trim() || undefined,
      datasourceId: props.datasourceId,
      database: props.database || undefined,
    });
    ElMessage.success(`表 ${table} 创建成功`);
    emit("created", props.database, table);
    emit("update:modelValue", false);
  } catch (e) {
    // 建表失败原因（内核不支持、类型/长度被拒等）要原样给出，用户据此改设计
    error.value = String((e as Error)?.message ?? e);
  } finally {
    busy.value = false;
  }
}
</script>

<template>
  <ReDialog
    :model-value="modelValue"
    title="新建表（设计表）"
    width="min(1000px, 96vw)"
    @update:model-value="(v: unknown) => emit('update:modelValue', Boolean(v))"
  >
    <div class="ct">
      <div class="ct-head">
        <div class="ct-form__item">
          <label>目标库</label>
          <ReInput :model-value="database" disabled />
        </div>
        <div class="ct-form__item">
          <label>表名</label>
          <ReInput v-model="name" placeholder="请输入表名" />
        </div>
        <div class="ct-form__item ct-form__item--wide">
          <label>表注释</label>
          <ReInput v-model="remark" placeholder="请输入表注释" />
        </div>
      </div>

      <div class="ct-grid-bar">
        <span class="ct-grid-bar__title">列设计</span>
        <span class="ct-grid-bar__hint">勾主键 / 自增会自动把该列置为「不可空」</span>
        <span class="ct-spacer" />
        <ReButton layout="square" type="primary" icon="Plus" tip="添加一列" @click="addRow" />
      </div>

      <div class="ct-grid">
        <div class="ct-grid__head">
          <span>#</span>
          <span>字段名</span>
          <span>类型</span>
          <span>长度</span>
          <span>小数位</span>
          <span>可空</span>
          <span>主键</span>
          <span>自增</span>
          <span>默认值</span>
          <span>注释</span>
          <span>操作</span>
        </div>
        <div v-for="(row, i) in rows" :key="row.key" class="ct-grid__row">
          <span class="ct-grid__idx">{{ i + 1 }}</span>
          <ReInput v-model="row.name" class="ct-mono" placeholder="字段名" />
          <ReSelect v-model="row.type" :options="typeOptions" filterable />
          <!-- 长度 / 小数位：该类型用不上时留一个占位横线，而不是空一格 ——
               空格子看起来像「没渲染完」，横线才说明是「这个类型没有这一项」。 -->
          <ReInputNumber
            v-if="typeNeedsSize(row.type)"
            :model-value="row.size ?? undefined"
            :min="1"
            :max="65535"
            controls-position="right"
            placeholder="长度"
            @update:model-value="row.size = $event ?? null"
          />
          <span v-else class="ct-na" aria-hidden="true">—</span>
          <ReInputNumber
            v-if="typeAllowsScale(row.type)"
            :model-value="row.scale ?? undefined"
            :min="0"
            :max="30"
            controls-position="right"
            placeholder="位"
            @update:model-value="row.scale = $event ?? null"
          />
          <span v-else class="ct-na" aria-hidden="true">—</span>
          <!-- 布尔三列用同一套分段单选（与数据库控制台的开关同源，见 utils/columnTypes 同款口径），
               但格子只有 78~92px，必须配 ct-bool 这层「格子内」样式（见文件末尾）。
               少了它，re-kit 给单项的 64px min-width 会让三组溢出轨道、互相叠住。 -->
          <ReRadioGroup
            v-model="row.nullable"
            class="ct-bool"
            :disabled="row.primaryKey || row.autoIncrement"
            size="small"
          >
            <ReRadioButton :value="true">是</ReRadioButton>
            <ReRadioButton :value="false">否</ReRadioButton>
          </ReRadioGroup>
          <ReRadioGroup class="ct-bool" :model-value="row.primaryKey" size="small" @update:model-value="togglePk(row, $event)">
            <ReRadioButton :value="true">是</ReRadioButton>
            <ReRadioButton :value="false">否</ReRadioButton>
          </ReRadioGroup>
          <ReRadioGroup class="ct-bool" :model-value="row.autoIncrement" size="small" @update:model-value="toggleAuto(row, $event)">
            <ReRadioButton :value="true">是</ReRadioButton>
            <ReRadioButton :value="false">否</ReRadioButton>
          </ReRadioGroup>
          <ReInput v-model="row.defaultValue" class="ct-mono" placeholder="默认值" />
          <ReInput v-model="row.comment" placeholder="列注释" />
          <span class="ct-grid__ops">
            <ReButton icon="Delete" layout="square" type="danger" tip="删除该列" @click="removeRow(i)" />
          </span>
          <!-- 枚举取值 / 小数位提示单独占一行，不为它们再加列 -->
          <div v-if="ENUM_LIKE_TYPES.has(row.type)" class="ct-grid__sub">
            <span class="ct-grid__sub-label">{{ row.type }} 取值</span>
            <ReInput v-model="row.enumText" placeholder="a, b, c（逗号分隔，必填）" />
          </div>
        </div>
        <p v-if="rows.length === 0" class="ct-grid__empty">还没有列，点右上角「添加一列」开始设计</p>
      </div>

      <p class="ct-form__tip">
        引号、列注释与自增写法由后端按目标库内核选择（MySQL 用反引号与 AUTO_INCREMENT，
        H2 / PostgreSQL 用双引号与 GENERATED BY DEFAULT AS IDENTITY），这里只描述结构。
      </p>
      <p v-if="error" class="ct-form__error">{{ error }}</p>
    </div>
    <template #footer>
      <ReButton @click="emit('update:modelValue', false)">取消</ReButton>
      <ReButton type="primary" :loading="busy" :disabled="!canSubmit" @click="submit">创建</ReButton>
    </template>
  </ReDialog>
</template>

