<!--
  新建表对话框（数据库管理器专用）。

  <p>与 {@link CreateTableDialog}（数据源中心的建表/补列）是**两件事**，不要合并：
  那一个走 hub 的 DDL 接口，列定义是结构化的、能推断类型与跨方言拼装；
  这一个面向 Navicat 式手工建表，列定义由用户直接写 SQL 片段，
  且必须支持指定目标库（hub 的 DDL 接口只认连接默认库，没有 database 参数）。</p>

  <p>因此这里**不在前端拼 CREATE TABLE**：反引号引号与内联 COMMENT 都是 MySQL 专属，
  H2/PostgreSQL 上会直接语法错。整条语句交后端 {@link DbDialectSupport.createTable}
  按内核选写法。</p>
-->
<script setup lang="ts">
import { computed, ref, watch } from "vue";
import { ElMessage } from "element-plus";
import ReButton from "@repo/ui/re-button";
import ReDialog from "@repo/ui/re-dialog";
import ReInput from "@repo/ui/re-input";
import { createDbTable } from "../../api/manageConsoles";

const props = withDefaults(
  defineProps<{
    /** 对话框可见性（v-model） */
    modelValue: boolean;
    /** 目标库名 */
    database?: string;
    /** 数据源 ID */
    datasourceId?: number;
  }>(),
  {
    database: "",
    datasourceId: undefined,
  },
);

const emit = defineEmits<{
  (e: "update:modelValue", value: boolean): void;
  /** 建表成功（带上库名，宿主据此刷新对应库的表树） */
  (e: "created", database: string): void;
}>();

const name = ref("");
const remark = ref("");
const fields = ref("");
const busy = ref(false);
const error = ref("");

/** 表名与列定义齐了才能建 */
const canSubmit = computed(() => Boolean(name.value.trim()) && Boolean(fields.value.trim()));

/** 每次打开都清空上一次的内容与报错 */
watch(
  () => props.modelValue,
  open => {
    if (!open) {
      return;
    }
    name.value = "";
    remark.value = "";
    fields.value = "";
    error.value = "";
  },
);

async function submit(): Promise<void> {
  const table = name.value.trim();
  if (!canSubmit.value) {
    return;
  }
  busy.value = true;
  error.value = "";
  try {
    await createDbTable({
      table,
      fields: fields.value.trim(),
      comment: remark.value.trim() || undefined,
      datasourceId: props.datasourceId,
      database: props.database || undefined,
    });
    ElMessage.success(`表 ${table} 创建成功`);
    emit("created", props.database);
    emit("update:modelValue", false);
  } catch (e) {
    // 建表失败原因（语法、内核不支持等）要原样给出，用户据此改列定义
    error.value = String((e as Error)?.message ?? e);
  } finally {
    busy.value = false;
  }
}
</script>

<template>
  <ReDialog :model-value="modelValue" title="新建表" width="600px" @update:model-value="(v: unknown) => emit('update:modelValue', Boolean(v))">
    <div class="ct-form">
      <div class="ct-form__item">
        <label>目标库</label>
        <ReInput :model-value="database" disabled />
      </div>
      <div class="ct-form__item">
        <label>表名</label>
        <ReInput v-model="name" placeholder="请输入表名" />
      </div>
      <div class="ct-form__item">
        <label>表注释</label>
        <ReInput v-model="remark" placeholder="请输入表注释" />
      </div>
      <div class="ct-form__item">
        <label>初始字段</label>
        <ReInput
          v-model="fields"
          type="textarea"
          :rows="4"
          placeholder="id BIGINT PRIMARY KEY,&#10;name VARCHAR(255) NOT NULL,&#10;created_at TIMESTAMP"
        />
      </div>
      <p class="ct-form__tip">
        字段按当前数据库方言执行：MySQL 可写 AUTO_INCREMENT，H2/PostgreSQL 请用
        GENERATED BY DEFAULT AS IDENTITY。列之间用英文逗号分隔。
      </p>
      <p v-if="error" class="ct-form__error">{{ error }}</p>
    </div>
    <template #footer>
      <ReButton @click="emit('update:modelValue', false)">取消</ReButton>
      <ReButton type="primary" :loading="busy" :disabled="!canSubmit" @click="submit">创建</ReButton>
    </template>
  </ReDialog>
</template>

