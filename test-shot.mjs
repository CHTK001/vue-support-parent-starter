import { chromium } from 'playwright';
const dir = 'G:/work/test-shots';
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  await p.goto('http://localhost:7788', { timeout: 20000, waitUntil: 'networkidle' });
  await p.waitForSelector('.connection-form', { timeout: 15000 });
  await p.screenshot({ path: dir + '/01-home.png' });
  await p.click('text=自定义模式');
  await p.waitForTimeout(1000);
  await p.fill('input[placeholder="192.168.1.100"]', '127.0.0.1');
  await p.fill('input[type="number"]', '2222');
  await p.fill('input[placeholder="admin / root"]', 'testuser');
  await p.fill('input[type="password"]', 'testpass');
  await p.screenshot({ path: dir + '/02-form-filled.png' });
  const btns = await p.$$('.el-button:has-text("连接")');
  if (btns.length > 1) await btns[1].click(); else await p.click('.el-button:has-text("连接")');
  await p.waitForSelector('.xterm', { timeout: 30000 });
  await p.waitForTimeout(3000);
  await p.screenshot({ path: dir + '/03-ssh-viewer.png' });
  console.log('截图完成');
  await b.close();
})();